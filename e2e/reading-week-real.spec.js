async function expectInputBounds(input) {
  expect(await input.evaluate(el => {
    const rect = el.getBoundingClientRect(), box = el.closest('.dew-input').getBoundingClientRect()
    return rect.left >= box.left && rect.right <= box.right + 1 && el.scrollWidth <= el.clientWidth + 1
  })).toBeTruthy()
}
async function login(page, request, user = 'stu1', admin = false, dark = false) {
  const response = await request.post(API + (admin ? '/auth/admin_login' : '/auth/login'), { data: { User_Email: user + '@seed.dev', User_Password: crypto.createHash('md5').update('12345678').digest('hex') } })
  expect(response.ok()).toBeTruthy()
  const data = await response.json()
  await page.context().addInitScript(({ data, admin, dark }) => {
    const prefix = admin ? 'bme-admin-' : 'bme-user-'
    localStorage.setItem(prefix + 'token', data.token)
    localStorage.setItem('themeInitialized', 'true')
    localStorage.setItem(prefix + 'state', JSON.stringify({ user: data, token: data.token, isLogin: true, isDarkMode: dark, checkinInfo: {} }))
  }, { data, admin, dark })
  return { Authorization: 'Bearer ' + data.token }
}
