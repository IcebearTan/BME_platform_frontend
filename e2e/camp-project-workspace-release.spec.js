import { test, expect } from '@playwright/test'

const BASE = 'http://127.0.0.1:18096/AMEII', API = 'http://127.0.0.1:5016'
const nav = (page, name) => page.getByRole('navigation', { name: '项目营功能' }).getByRole('button', { name, exact: true })
async function enter(page, name) {
  await page.goto(`${BASE}/dev/project-workspace`)
  await page.locator('.preview-roles .dew-card').filter({ has: page.getByRole('heading', { name, exact: true }) }).getByRole('button', { name: '进入工作台' }).click()
  await expect(page.locator('.project-workspace')).toBeVisible()
  await expect(page.locator('.pws-loading')).toHaveCount(0)
}
async function routeWithinApp(page, query) {
  await page.evaluate(query => {
    history.pushState({}, '', `/AMEII/camp?${query}`)
    dispatchEvent(new PopStateEvent('popstate', { state: history.state }))
  }, query)
}
const camps = async request => (await (await request.get(`${API}/preview/health`)).json()).camps

test('同营期内的节点通知直接切换项目，老师同页切换节点也同步展开', async ({ page }) => {
  await enter(page, '负责人演示'); await nav(page, '节点与交付').click()
  await expect(page.locator('.ms-body')).toBeVisible()
  await routeWithinApp(page, 'sid=1&scope=project&tab=delivery&node=5')
  await expect(page).toHaveURL(/unit=2/)
  await expect(page.locator('.pws-page-heading')).toContainText('质子治疗计划优化')
  await expect(page.locator('.pm-node-nav [aria-current=step]')).toContainText('样机测试')
  await page.goBack()
  await expect(page.locator('.pws-page-heading')).toContainText('智能肺康复口琴')
  await enter(page, '管理老师演示')
  await routeWithinApp(page, 'sid=1&scope=project&tab=delivery&node=1')
  await expect(page).toHaveURL(/unit=1/)
  await expect(page.locator('.el-collapse-item.is-active')).toContainText('需求规格书')
  await routeWithinApp(page, 'sid=1&scope=project&unit=1&tab=delivery&node=3')
  await expect(page.locator('.el-collapse-item.is-active')).toContainText('结题报告')
})

test('通知解析的延迟响应不能覆盖后续导航，非法通知不展示提交表单', async ({ page }) => {
  await enter(page, '负责人演示')
  let release
  const pending = new Promise(resolve => { release = resolve })
  let requested
  const started = new Promise(resolve => { requested = resolve })
  await page.route(`${API}/camp/projects/1/node-target/5`, async route => { requested(); await pending; await route.continue() })
  await routeWithinApp(page, 'sid=1&scope=project&tab=delivery&node=5')
  await started
  await routeWithinApp(page, 'sid=1&scope=project&unit=1&tab=overview')
  release()
  await expect(page.locator('.pwo')).toBeVisible()
  await expect(page).toHaveURL(/unit=1&tab=overview/)
  await routeWithinApp(page, 'sid=1&scope=project&tab=delivery&node=999999')
  await expect(page.locator('.pws-error')).toBeVisible()
  await expect(page.locator('.submit-box')).toHaveCount(0)
  await nav(page, '工作概览').click()
  await expect(page.locator('.pwo')).toBeVisible()
})

test('项目营老师名单展示项目职责，实际加人使用成员身份', async ({ page }) => {
  await enter(page, '管理老师演示'); await nav(page, '人员与组队').click()
  const list = page.locator('.teacher-members')
  await expect(list).toContainText('智能肺康复口琴 · 负责人')
  await expect(list.getByText('导生', { exact: true })).toHaveCount(0)
  await expect(list.locator('.mentor-select')).toHaveCount(0)
  await expect(list.locator('.member-row').filter({ hasText: '负责人演示' }).getByRole('button', { name: '移除', exact: true })).toHaveCount(0)
  const row = list.locator('.member-row').filter({ hasText: '待入营演示' })
  if (await row.count()) {
    await row.getByRole('button', { name: '移除', exact: true }).click()
    await page.getByRole('button', { name: '移除', exact: true }).last().click()
    await expect(row).toHaveCount(0)
  }
  await list.getByRole('button', { name: '加成员', exact: true }).click()
  await page.getByPlaceholder('输入姓名或邮箱搜索').fill('待入营演示')
  await page.locator('.dew-dialog').getByRole('button', { name: '搜索', exact: true }).click()
  await page.locator('.cand-row').filter({ hasText: '待入营演示' }).click()
  const saved = page.waitForResponse(r => r.url().includes('/members/batch') && r.request().method() === 'POST')
  await page.getByRole('button', { name: '加入（1）', exact: true }).click()
  const response = await saved
  expect(response.request().postDataJSON().items[0].role).toBe('member')
  expect((await response.json()).added).toBe(1)
  await expect(row).toContainText('未加入项目')
  await row.getByRole('button', { name: '移除', exact: true }).click()
  await page.getByRole('button', { name: '移除', exact: true }).last().click()
  await expect(row).toHaveCount(0)
  await list.getByRole('button', { name: '智能肺康复口琴 · 负责人', exact: true }).click()
  await expect(page.locator('.pwr')).toContainText('负责人演示')
  await expect(page.locator('.pws-page-heading')).toContainText('项目成员')
})

test('申报与组队入口分阶段展示，组队变更后人数及时刷新', async ({ page, request }) => {
  const ids = await camps(request)
  await enter(page, '负责人演示'); await page.goto(`${BASE}/camp?sid=${ids.upcoming}`)
  await nav(page, '申报项目').click()
  await expect(page.getByPlaceholder('如：智能输液监护系统')).toBeVisible()
  await expect(nav(page, '项目意向')).toHaveCount(0)
  await page.goto(`${BASE}/camp?sid=${ids.selecting}`)
  await expect(nav(page, '申报项目')).toHaveCount(0)
  await nav(page, '项目意向').click()
  await expect(page.locator('.tray-title')).toHaveText('我的项目意向')
  await nav(page, '项目成员').click()
  const candidate = page.locator('.roster-row').filter({ hasText: '双身份演示' })
  await expect(page.locator('.roster-footer')).toBeVisible()
  if (await candidate.getByRole('button', { name: '移出', exact: true }).count()) {
    await candidate.getByRole('button', { name: '移出', exact: true }).click()
    await page.getByRole('button', { name: '提交变更', exact: true }).click()
    await expect(page.locator('.pws-page-heading')).toContainText('2人')
    await expect(candidate.getByRole('button', { name: '加入', exact: true })).toBeVisible()
  }
  await candidate.getByRole('button', { name: '加入', exact: true }).click()
  await page.getByRole('button', { name: '提交变更', exact: true }).click()
  await expect(page.locator('.pws-page-heading')).toContainText('3人')
  await expect(page.locator('.roster-footer')).toBeVisible()
  const member = page.locator('.roster-row').filter({ hasText: '双身份演示' })
  await member.getByRole('button', { name: '移出', exact: true }).click()
  await page.getByRole('button', { name: '提交变更', exact: true }).click()
  await expect(page.locator('.pws-page-heading')).toContainText('2人')
})

test('开启周考勤和请假后，个人统计、负责人周表及老师审批可用', async ({ page, request }) => {
  const ids = await camps(request)
  await enter(page, '负责人演示'); await page.goto(`${BASE}/camp?sid=${ids.weekly}`)
  await expect(page.locator('.pws-attendance')).toContainText('累计出勤')
  await nav(page, '周考勤').click()
  await expect(page.locator('.pwa-table')).toContainText('成员演示')
  await enter(page, '成员演示'); await page.goto(`${BASE}/camp?sid=${ids.weekly}`)
  await expect(nav(page, '周考勤')).toHaveCount(0)
  await expect(page.locator('.pws-attendance')).toBeVisible()
  await nav(page, '我的请假').click()
  const day = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Shanghai' }).format(new Date())
  await page.getByPlaceholder('开始日期').fill(day)
  await page.getByPlaceholder('结束日期').fill(day)
  await page.getByPlaceholder('结束日期').press('Tab')
  const marker = `项目营请假检查 ${Date.now()}`
  await page.getByPlaceholder('请简要说明请假原因').fill(marker)
  await page.getByRole('button', { name: '提交申请', exact: true }).click()
  await expect(page.locator('.leave-list')).toContainText(marker)
  await enter(page, '管理老师演示'); await page.goto(`${BASE}/camp?sid=${ids.weekly}&tab=leave`)
  const row = page.locator('.mentor-leave .dew-card').filter({ has: page.locator('.reason', { hasText: marker }) }).last()
  await row.getByRole('button', { name: '批准', exact: true }).click()
  await expect(row).toContainText('已批准')
  await nav(page, '全营考勤').click()
  await expect(page.locator('.mentor-dashboard')).toContainText('全营出勤周报')
  await expect(page.locator('.mentor-dashboard')).toContainText('成员演示')
  await enter(page, '成员演示'); await page.goto(`${BASE}/camp?sid=${ids.weekly}&tab=leave`)
  await expect(page.locator('.leave-list .dew-card').filter({ hasText: marker })).toContainText('已批准')
})

test('关闭能力时不发起考勤请求，结营老师没有人员和公告写入口', async ({ page, request }) => {
  const ids = await camps(request), attendance = []
  page.on('request', r => { if (r.url().includes('/attendance/')) attendance.push(r.url()) })
  await enter(page, '成员演示')
  await expect(page.locator('.pwo')).toBeVisible()
  expect(attendance).toEqual([])
  await expect(nav(page, '我的请假')).toHaveCount(0)
  await expect(page.locator('.pws-attendance')).toHaveCount(0)
  await enter(page, '管理老师演示'); await page.goto(`${BASE}/camp?sid=${ids.archived}&tab=members`)
  await expect(page.locator('.pws-frozen-members')).toContainText('负责人演示')
  await expect(page.getByRole('button', { name: '加成员', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '移除', exact: true })).toHaveCount(0)
  await expect(nav(page, '报名审批')).toHaveCount(0)
  await nav(page, '营期公告').click()
  await expect(page.locator('.pwl-muted')).toContainText('本营暂无公告')
  await expect(page.getByRole('button', { name: '发布公告', exact: true })).toHaveCount(0)
})
