  const added=await request.post(`${API}/project-core/projects/${pid}/members`,{headers,data:{action:'add',user_id:member.user_id,expected_version:metadata.version,reason:'本地跨期检查成员',idempotency_key:'cross-period-member-'+Date.now()}})
  expect(added.status()).toBe(200)
  await page.getByRole('navigation',{name:'项目功能'}).getByRole('button',{name:'参加的营期',exact:true}).click()
  await page.getByRole('button',{name:'申请参加营期',exact:true}).click()
  await page.getByRole('dialog').last().getByRole('combobox').click()
  await page.getByText('项目营 · 独立项目关联演示',{exact:true}).last().click()
