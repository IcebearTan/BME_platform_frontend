test('真实项目记录上传附件、下载及通知定位',async({page,request})=>{
  await login(page);await page.goto(`${BASE}/my-projects`)
  await page.locator('.pd-projects .dew-card').filter({hasText:'独立项目 · 日历试用'}).getByRole('button',{name:'进入项目'}).click()
  await page.getByRole('navigation',{name:'项目功能'}).getByRole('button',{name:'记录与成果',exact:true}).click()
  await page.getByRole('button',{name:'新增记录',exact:true}).click()
  const marker=`研发记录 ${Date.now()}`
  await page.getByPlaceholder('记录标题',{exact:true}).fill(marker)
  await page.getByPlaceholder('记录过程、结论和下一步').fill('实际验证结果与可下载材料')
  await page.locator('.pr-form input[type=file]').setInputFiles({name:'project-record.txt',mimeType:'text/plain',buffer:Buffer.from('project-record-real-api')})
  await page.getByPlaceholder('说明本次新增或调整').fill('真实附件检查')
  const saved=page.waitForResponse(r=>r.url().includes('/project-core/projects/')&&r.url().endsWith('/records')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'保存记录',exact:true}).click()
  const response=await saved;expect(response.status()).toBe(200)
  const row=page.locator('.pr-record').filter({hasText:marker});await expect(row).toContainText('project-record.txt')
  const token=page.waitForResponse(r=>r.url().includes('/project-core/files/')&&r.url().includes('/token'))
  await row.getByRole('button',{name:'project-record.txt',exact:true}).click()
  const url=(await(await token).json()).url
  const download=await request.get('http://127.0.0.1:5016'+url)
  expect(download.status()).toBe(200);expect((await download.body()).toString()).toBe('project-record-real-api')
  const recordId=(await response.json()).record.id
  await login(page,'成员演示')
  const bearer=await page.evaluate(()=>localStorage.getItem('bme-user-token'))
  const inbox=await(await request.get('http://127.0.0.1:5016/notification/list?category=system&page_size=100',{headers:{Authorization:'Bearer '+bearer}})).json()
  const candidates=inbox.notifications||inbox.data?.notifications||[]
  let eventId
  for(const notification of candidates.filter(n=>n.source_type==='project_core')){
    const target=await(await request.get(`http://127.0.0.1:5016/project-core/changes/${notification.source_id}/target`,{headers:{Authorization:'Bearer '+bearer}})).json()
    if(target.record_id===recordId){eventId=notification.source_id;break}
  }
  expect(eventId).toBeTruthy()
  await page.goto(`${BASE}/project-activity/${eventId}`)
  await expect(page).toHaveURL(new RegExp('record='+recordId))
  await expect(page.locator('.pr-record').filter({hasText:marker})).toBeVisible()
})

