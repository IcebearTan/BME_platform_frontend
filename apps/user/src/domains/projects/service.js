import api,{API_URL} from '../../api'
const base = '/project-core/projects'
export const projectService = {
  status: () => api.get('/project-core/status').then(r => r.data),
  list: () => api.get(base).then(r => r.data),
  create: data => api.post(base, data).then(r => r.data),
  detail: id => api.get(`${base}/${id}`).then(r => r.data),
  update: (id, data) => api.patch(`${base}/${id}`, data).then(r => r.data),
  members: id => api.get(`${base}/${id}/members`).then(r => r.data),
  candidates: (id, keyword) => api.get(`${base}/${id}/candidates`, { params: { keyword } }).then(r => r.data),
  changeMember: (id, data) => api.post(`${base}/${id}/members`, data).then(r => r.data),
  calendar: (id, params) => api.get(`${base}/${id}/calendar`, { params }).then(r => r.data),
  previewZero: (id, zero_date) => api.post(`${base}/${id}/zero-date/preview`, { zero_date }).then(r => r.data),
  changeZero: (id, data) => api.patch(`${base}/${id}/zero-date`, data).then(r => r.data),
  saveEntry: (id, source, data, entryId) => (entryId ? api.patch(`${base}/${id}/schedule/${source}/${entryId}`, data) : api.post(`${base}/${id}/schedule/${source}`, data)).then(r => r.data),
  context: (id,binding,view) => api.get(`${base}/${id}/context`,{params:{binding,view}}).then(r=>r.data),
  camps: id => api.get(`${base}/${id}/camps`).then(r=>r.data),
  availableCamps: () => api.get('/project-core/camps/available').then(r=>r.data),
  requestCamp: (id,data) => api.post(`${base}/${id}/camps`,data).then(r=>r.data),
  operateCamp: (id,bid,data) => api.post(`${base}/${id}/camps/${bid}`,data).then(r=>r.data),
  requestParticipants: (id,bid,data) => api.post(`${base}/${id}/camps/${bid}/participants-request`,data).then(r=>r.data),
  campProjects: sid => api.get(`/project-core/camps/${sid}/projects`).then(r=>r.data),
  records: (id,params) => api.get(`${base}/${id}/records`,{params}).then(r=>r.data),
  saveRecord: (id,data,files,rid) => {const form=new FormData();form.append('metadata',JSON.stringify(data));for(const file of files)form.append('files',file);return(rid?api.patch(`${base}/${id}/records/${rid}`,form):api.post(`${base}/${id}/records`,form)).then(r=>r.data)},
  verifyRecord: (id,rid,data) => api.post(`${base}/${id}/records/${rid}/verify`,data).then(r=>r.data),
  fileUrl: (aid,binding) => api.get(`/project-core/files/${aid}/token`,{params:{binding}}).then(r=>(API_URL||'').replace(/\/$/,'')+r.data.url),
  history: id => api.get(`${base}/${id}/history`).then(r=>r.data),
  target: id => api.get(`/project-core/changes/${id}/target`).then(r=>r.data),
  resolveLegacy: uid => api.get(`/project-core/legacy/${uid}/resolve`).then(r=>r.data),
  legacyCandidates: () => api.get('/project-core/legacy-candidates').then(r=>r.data),
  migrationPreview: uid => api.get(`/project-core/legacy/${uid}/preview`).then(r=>r.data),
  migrate: (uid,data) => api.post(`/project-core/legacy/${uid}/migrate`,data).then(r=>r.data),
  publish: (id,data) => api.post(`${base}/${id}/publish`,data).then(r=>r.data),
  bindingArchive: (id,bid) => api.get(`${base}/${id}/camps/${bid}/archive`).then(r=>r.data),
}
export const mutation = (project, fields) => ({ ...fields, expected_version: project.version, idempotency_key: crypto.randomUUID() })
